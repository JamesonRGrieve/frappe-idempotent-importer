"""Pure Ecwid → desired ERPNext state, one mapper per kind, in the shared field contract. Ported from
wp-woo-idempotent-importer's Ecwid mappers; Ecwid's variations (``combinations``), attributes, coupon types,
order statuses, taxes and positional refunds are translated here. Identities arrive scoped to the
connection, with Ecwid's id as ``source_id``. Money arrives as JSON numbers, read exactly as spelled."""

