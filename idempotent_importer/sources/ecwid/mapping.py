WEIGHT_UNITS = {"GRAM": "g", "KILOGRAM": "kg", "OUNCE": "oz", "POUND": "lbs"}
UPC, BRAND = "UPC", "BRAND"
# Payment statuses of a paid order; cancelled and incomplete (unfinished online payment) orders aren't sales.
PAID = frozenset({"PAID", "PARTIALLY_REFUNDED", "REFUNDED"})
NOT_SALES = frozenset({"CANCELLED", "INCOMPLETE"})
ACTIVE = "ACTIVE"
COUPON_TYPES = {"PERCENT": "percentage", "ABS": "amount"}
ANY_CUSTOMER = "UNLIMITED"
SINGLE_USE, ONCE_PER_CUSTOMER = "SINGLE", "ONCEPERCUSTOMER"
# Ecwid's store front page category: the products shown there, which has no Item Group.
FRONT_PAGE_CATEGORY = 0
PUBLISHED = "published"
MAX_RATING = 5


@dataclass(frozen=True)
class Context:
	config: ConnectionConfig

	def gid(self, type_: str, id_: int | str) -> str:
		return self.config.identity(type_, id_)

	def variant(self, product_id: int | str, combination_id: int | None) -> str:
		"""A variation by its Ecwid id (what an order item names as ``combinationId``); a product without
		variations has one variant of its own."""
		return self.gid("Variant", f"{product_id}-base" if combination_id is None else combination_id)


def amount_of(node: Node | None, field: str) -> Decimal:
	return (node.optional_decimal(field) if node else None) or Decimal(0)


def set_amount(node: Node | None, field: str) -> Decimal | None:
	value = node.optional_decimal(field) if node else None
	return value if value else None


def linked(node: Node, field: str) -> int | None:
	"""A positive id field (Ecwid sends 0 or leaves it out when nothing is linked)."""
	value = node.optional_integer(field)
	return value if value is not None and value > 0 else None


def slug_of(node: Node, name: str) -> str:
	return node.optional_string("customSlug") or node.optional_string("autogeneratedSlug") or slugify(name)


def legacy(url: str | None) -> tuple[str, ...]:
	"""An object's old storefront path; none for a hashbang link (``/#!/…``) or the home page."""
	path = None if url is None or "#" in url else path_of(url)
	return (path,) if path else ()


def attribute(node: Node, attribute_type: str) -> str | None:
	"""The value of a product's or variation's attribute of an Ecwid type (``UPC``, ``BRAND``)."""
	attributes = node.children("attributes") if isinstance(node.get("attributes"), list) else []
	return next(
		(a.optional_string("value") for a in attributes if a.optional_string("type") == attribute_type), None
	)


def ecwid_address(address_type: str, person: Node | None, email: str | None) -> Fields | None:
	if person is None:
		return None
	line1, _, line2 = (person.optional_string("street") or "").partition("\n")
	city = person.optional_string("city")
	if not line1.strip() or not city:
		return None
	return address_fields(
		Address(
			address_type=address_type,
			name=person.optional_string("name"),
			company=person.optional_string("companyName"),
			line1=line1.strip(),
			line2=line2.strip() or None,
			city=city,
			state=person.optional_string("stateOrProvinceCode")
			or person.optional_string("stateOrProvinceName"),
			postcode=person.optional_string("postalCode"),
			country_code=person.optional_string("countryCode"),
			email=email,
			phone=person.optional_string("phone"),
		)
	)


def taxes_of(node: Node, field: str, amount_field: str = "total") -> list[tuple[str, Decimal]]:
	"""Ecwid taxes (``[{name, value, total, …}]``), the amount read from ``amount_field`` (else ``total``);
	taxes that charged nothing are left out."""
	taxes = node.children(field) if isinstance(node.get(field), list) else []
	found = [
		(t.optional_string("name") or "Tax", t.optional_decimal(amount_field) or amount_of(t, "total"))
		for t in taxes
	]
	return [(name, amount) for name, amount in found if amount]


class CategoryMapper:
	"""A category → an Item Group: name, slug, description, image and parent; its old URL redirects to it."""

	kind = Kind.COLLECTION
	version = 1

	def __init__(self, context: Context) -> None:
		self._context = context

	def map(self, node: Node) -> Desired | None:
		name = node.string("name")
		parent = linked(node, "parentId")
		fields: Fields = {
			"name": name,
			"slug": slug_of(node, name),
			"parent": self._context.gid("Category", parent) if parent is not None else None,
			"description": node.optional_string("description"),
			"image": node.optional_string("originalImageUrl"),
		}
		return Desired(self.kind, node.id(), fields, legacy(node.optional_string("url")))


class ProductMapper:
	"""A product → an Item: one (no variations) or a template with a variant per variation, whose attributes
	are the options it selects. A compare-to price above the price makes it the price and the price the sale.
	Stock follows ``unlimited`` and ``quantity``; a product that needs no shipping isn't a stock item. The UPC
	attribute is the barcode and the brand attribute the Brand. A disabled product is unpublished; a gift card
	is Unsupported."""

	kind = Kind.PRODUCT
	version = 1

	def __init__(self, context: Context) -> None:
		self._context = context

	def map(self, node: Node) -> Desired | None:
		title = node.string("name")
		if node.get("isGiftCard") is True:
			raise Unsupported("gift cards have no ERPNext home (coverage/ecwid.md)")
		combinations = sorted(
			node.children("combinations"),
			key=lambda c: (c.optional_integer("combinationNumber") or 0, c.integer("id")),
		)
		simple = not combinations
		unit = WEIGHT_UNITS.get((node.optional_string("weight_unit") or "").strip().upper())
		variants = (
			[self._variant(node, node, None, unit)]
			if simple
			else [self._variant(node, c, c.integer("id"), unit) for c in combinations]
		)
		warnings: list[str] = []
		if unit is None and set_amount(node, "weight") is not None:
			warnings.append(
				f"a weight in {node.optional_string('weight_unit') or 'no unit'}, which has no ERPNext UOM"
			)
		options = node.children("options") if simple and isinstance(node.get("options"), list) else []
		if any(
			o.optional_string("type") in ("SELECT", "RADIO", "CHECKBOX", "SIZE", "SWATCHES") for o in options
		):
			warnings.append("options without variations, which Items can't ask for")
		if node.get("wholesalePrices"):
			warnings.append("wholesale price tiers; the Item has one price")
		first = variants[0]
		shipped = node.get("isShippingRequired") is not False
		fields: Fields = {
			"type": "simple" if simple else "variable",
			"name": title,
			"slug": slug_of(node, title),
			"description": node.optional_string("description"),
			"short_description": node.optional_string("subtitle"),
			"sku": first["sku"] if simple else None,
			"barcode": first["barcode"] if simple else None,
			"brand": attribute(node, BRAND),
			"collections": [
				self._context.gid("Category", c)
				for c in node.integers("categoryIds")
				if c != FRONT_PAGE_CATEGORY
			],
			"images": images(node),
			"published": node.get("enabled") is not False,
			"is_stock_item": shipped and any(v["stock_qty"] is not None for v in variants),
			"weight": first["weight"] if simple else None,
			"price": first["price"] if simple else None,
			"sale": first["sale"] if simple else None,
			"stock_qty": first["stock_qty"] if simple else None,
			"attributes": [] if simple else variant_attributes(variants),
			"specifications": [],
			"variants": [] if simple else list[Field](variants),
			"tags": [],
		}
		return Desired(self.kind, node.id(), fields, legacy(node.optional_string("url")), tuple(warnings))

	def _variant(self, product: Node, source: Node, combination_id: int | None, unit: str | None) -> Fields:
		chosen: dict[str, Field] = (
			{o.string("name"): o.string("value") for o in source.children("options")}
			if combination_id is not None
			else {}
		)
		price = source.optional_decimal("price") or product.decimal("price")
		compare_to = set_amount(source, "compareToPrice")
		on_sale = compare_to is not None and compare_to > price
		unlimited = (
			source.get("unlimited") if source.get("unlimited") is not None else product.get("unlimited")
		)
		weight = set_amount(source, "weight") or (
			set_amount(product, "weight") if combination_id is not None else None
		)
		return {
			"gid": self._context.variant(product.string("source_id"), combination_id),
			"sku": source.optional_string("sku"),
			"barcode": attribute(source, UPC),
			"attributes": chosen,
			"price": compare_to if on_sale and compare_to is not None else price,
			"sale": {"price": price, "from": None, "to": None} if on_sale else None,
			"stock_qty": None
			if unlimited is not False
			else Decimal(max(0, source.optional_integer("quantity") or 0)),
			"weight": {"value": weight.normalize(), "unit": unit} if unit and weight else None,
			"image": source.optional_string("originalImageUrl") if combination_id is not None else None,
			"enabled": True,
		}


def images(product: Node) -> list[Field]:
	"""The media images, the main one first, at full size with their alt text; else the main image alone."""
	media = product.child("media")
	entries = sorted(media.children("images") if media else [], key=lambda i: i.get("isMain") is not True)
	found: list[Field] = []
	for image in entries:
		alt = image.child("alt")
		url = image.optional_string("imageOriginalUrl")
		if url:
			found.append({"url": url, "alt": alt.optional_string("main") if alt else None})
	main = product.optional_string("originalImageUrl")
	return found or ([{"url": main, "alt": None}] if main else [])


class CustomerMapper:
	"""A customer → a Customer, its Contact, the billing address and the first saved shipping address."""

	kind = Kind.CUSTOMER
	version = 1

	def map(self, node: Node) -> Desired | None:
		email = (node.optional_string("email") or "").lower() or None
		person = node.child("billingPerson")
		first = person.optional_string("firstName") if person else None
		last = person.optional_string("lastName") if person else None
		name = person.optional_string("name") if person else None
		saved = node.children("shippingAddresses")
		addresses = [
			a
			for a in (
				ecwid_address("Billing", person, email),
				ecwid_address("Shipping", saved[0] if saved else None, None),
			)
			if a is not None
		]
		phones = sorted(
			(c for c in node.children("contacts") if c.optional_string("type") == "PHONE"),
			key=lambda c: c.get("default") is not True,
		)
		fields: Fields = {
			"name": name or " ".join(p for p in (first, last) if p) or email or node.string("source_id"),
			"type": "Individual",
			"first_name": first,
			"last_name": last,
			"company": (person.optional_string("companyName") if person else None),
			"email": email,
			"phone": (person.optional_string("phone") if person else None)
			or (phones[0].optional_string("contact") if phones else None),
			"addresses": list[Field](addresses),
		}
		return Desired(self.kind, node.id(), fields)


class DiscountMapper:
	"""An active discount coupon → a coupon Pricing Rule, when ERPNext applies it exactly: a percentage off
	(optionally of some products or categories) or an amount off the order, with its minimum subtotal, a
	single use, and its launch and expiry dates. Free shipping, an amount off some products, once-per-customer
	coupons, and coupons for new or repeat customers, some shipping methods or the front page are Unsupported."""

	kind = Kind.DISCOUNT
	version = 1

	def __init__(self, context: Context) -> None:
		self._context = context

	def map(self, node: Node) -> Desired | None:
		if node.optional_string("status") != ACTIVE:
			return None
		coupon_type = node.string("discountType")
		kind = COUPON_TYPES.get(coupon_type)
		if kind is None:
			raise Unsupported(f"a {coupon_type} coupon (ERPNext coupons can't discount shipping)")
		catalog = node.child("catalogLimit")
		products = catalog.integers("products") if catalog else []
		categories = catalog.integers("categories") if catalog else []
		if kind == "amount" and (products or categories):
			raise Unsupported("an amount off some products (Ecwid doesn't say per item or in total)")
		if FRONT_PAGE_CATEGORY in categories:
			raise Unsupported("a coupon for the store front page's products has no Item Group")
		if products and categories:
			raise Unsupported("a coupon for both products and categories has no single ERPNext pricing rule")
		customers = node.optional_string("applicationLimit") or ANY_CUSTOMER
		if customers != ANY_CUSTOMER:
			raise Unsupported(f"a coupon for {customers.lower()} customers has no ERPNext coupon equivalent")
		limit = node.child("shippingLimit")
		if limit is not None and limit.strings("shippingMethods"):
			raise Unsupported("a coupon for some shipping methods has no ERPNext coupon equivalent")
		uses = node.optional_string("usesLimit")
		if uses == ONCE_PER_CUSTOMER:
			raise Unsupported("a once-per-customer limit has no ERPNext coupon equivalent")
		discount = Discount(
			codes=[node.string("code")],
			description=node.optional_string("name") or node.string("code"),
			discount=kind,
			applies="items" if products else "groups" if categories else "transaction",
			value=amount_of(node, "discount"),
			items=[self._context.gid("Product", p) for p in products],
			groups=[self._context.gid("Category", c) for c in categories],
			min_amount=set_amount(node, "totalLimit"),
			valid_from=date_of(node.optional_time("launchDate") or node.optional_time("creationDate")),
			valid_upto=date_of(node.optional_time("expirationDate")),
			max_uses=1 if uses == SINGLE_USE else None,
		)
		return Desired(self.kind, node.id(), discount_fields(discount))


class OrderMapper:
	"""An order → an invoice with Ecwid's totals in the store's currency, numbered by its id: items at their
	prices before discounts on the variation's item, the order's discount, each tax summed by name over the
	items, shipping and surcharges, the shipping option, the handling fee and surcharges; refunds as credit
	notes (one adjustment line each: Ecwid doesn't say which items), and the tracking number, each shipping
	label and the private notes as comments. Paid orders are submitted; awaiting and custom payment statuses
	are drafts; cancelled and incomplete orders map to nothing. A gross-price order's taxes are included in
	its prices (``inclusive_charges``)."""

	kind = Kind.ORDER
	version = 2

	def __init__(self, context: Context) -> None:
		self._context = context

	def map(self, node: Node) -> Desired | None:
		payment_status = node.string("paymentStatus")
		if payment_status in NOT_SALES:
			return None
		currency = node.string("currency")
		order_id = node.string("source_id")
		submitted = payment_status in PAID
		email = (node.optional_string("email") or "").lower() or None
		customer = linked(node, "customerId")
		billing = node.child("billingPerson")
		inclusive = node.get("pricesIncludeTax") is True
		lines = [self._line(item, currency, inclusive=inclusive) for item in node.children("items")]
		if inclusive:
			lines, found = inclusive_charges(node, lines)
		else:
			found = charges(node)
		fields: Fields = {
			"number": order_id,
			"currency": currency,
			"created_at": node.time("createDate"),
			"submitted": submitted,
			"customer": self._context.gid("Customer", customer) if customer is not None else None,
			"guest": None
			if customer is not None
			else {
				"name": billing.optional_string("name") if billing else None,
				"email": email,
				"phone": billing.optional_string("phone") if billing else None,
			},
			"billing": ecwid_address("Billing", billing, email),
			"shipping": ecwid_address("Shipping", node.child("shippingPerson"), None),
			"lines": [line_fields(line) for line in lines],
			"discount": amount_of(node, "discount"),
			"charges": [charge_fields(charge) for charge in found],
			"total": amount_of(node, "total"),
			"payment": {
				"method": node.optional_string("paymentMethod") or "Ecwid",
				"reference": node.optional_string("externalTransactionId"),
				"date": node.time("createDate"),
			}
			if submitted
			else None,
			"refunds": [
				self._refund(refund, order_id, index, currency)
				for index, refund in enumerate(node.children("refunds"), start=1)
			]
			if submitted
			else [],
			"notes": self._notes(node, order_id),
			"remarks": node.optional_string("orderComments"),
		}
		if inclusive:
			fields["taxes_included"] = True
		return Desired(self.kind, node.id(), fields)

	def _line(self, item: Node, currency: str, *, inclusive: bool = False) -> OrderLine:
		"""An item at its price before discounts: without tax, or with it in a gross-price order."""
		product = linked(item, "productId")
		quantity = Decimal(item.integer("quantity"))
		chosen = ", ".join(
			f"{o.string('name')}: {value}"
			for o in (
				item.children("selectedOptions") if isinstance(item.get("selectedOptions"), list) else []
			)
			if (value := o.optional_string("value"))
		)
		name = item.optional_string("name") or item.optional_string("sku") or "Product"
		return order_line(
			self._context.gid("OrderItem", item.integer("id")),
			self._context.gid("Product", product) if product is not None else None,
			self._context.variant(product, linked(item, "combinationId")) if product is not None else None,
			f"{name} ({chosen})" if chosen else name,
			quantity,
			(
				item.decimal("price")
				if inclusive
				else item.optional_decimal("priceWithoutTax") or item.decimal("price")
			)
			* quantity,
			currency,
		)

	def _refund(self, refund: Node, order_id: str, position: int, currency: str) -> Field:
		"""Ecwid's refunds have no ids and are only ever added, so each is keyed by its place in the list."""
		gid = self._context.gid("Refund", f"{order_id}-{position}")
		amount = amount_of(refund, "amount")
		balance = refund_balance(f"{gid}#adjustment", amount, [], [], currency)
		return {
			"gid": gid,
			"date": refund.optional_time("date"),
			"reason": refund.optional_string("reason"),
			"amount": amount,
			"lines": [line_fields(balance)] if balance else [],
			"charges": [],
		}

	def _notes(self, order: Node, order_id: str) -> list[Field]:
		placed = order.time("createDate")
		notes: list[Field] = []
		tracking = order.optional_string("trackingNumber")
		if tracking:
			notes.append(
				self._note(
					f"Tracking/{order_id}-{tracking}", placed, None, f"Ecwid tracking number {tracking}"
				)
			)
		for shipment in order.children("shipments"):
			service = shipment.child("shippingService")
			label = shipment.child("tracking")
			number = label.optional_string("tracking_number") if label else None
			parts = [
				service.optional_string("carrierName") if service else None,
				f"tracking {number}" if number else None,
			]
			text = "Ecwid shipping label " + " ".join(p for p in parts if p)
			notes.append(
				self._note(
					f"Shipment/{order_id}-{shipment.string('id')}",
					shipment.optional_time("created") or placed,
					None,
					text.strip(),
				)
			)
		memo = order.optional_string("privateAdminNotes")
		if memo:
			notes.append(self._note(f"Memo/{order_id}", placed, "Staff", memo))
		return notes

	def _note(self, key: str, date: str, author: str | None, text: str) -> Field:
		type_, _, id_ = key.partition("/")
		return {
			"gid": self._context.gid(type_, id_),
			"date": date,
			"author": author,
			"text": text,
			"customer_note": False,
		}


def charges(order: Node) -> list[Charge]:
	"""Each tax summed by name over the items, the shipping and the surcharges (the order's tax total when Ecwid
	itemises none), then the shipping option, the handling fee and the surcharges, tax-exclusive."""
	surcharges = order.children("customSurcharges") if isinstance(order.get("customSurcharges"), list) else []
	taxes: dict[str, Decimal] = {}
	itemised = [
		*(
			tax
			for item in order.children("items")
			for tax in taxes_of(item, "taxes", "taxOnDiscountedSubtotal")
		),
		*taxes_of(order, "taxesOnShipping"),
		*(tax for surcharge in surcharges for tax in taxes_of(surcharge, "taxes")),
	]
	for name, amount in itemised:
		taxes[name] = taxes.get(name, Decimal(0)) + amount
	if not taxes and amount_of(order, "tax"):
		taxes["Tax"] = amount_of(order, "tax")
	found = [Charge(TAX, name, amount) for name, amount in taxes.items()]
	option = order.child("shippingOption")
	if option is not None:
		cost = option.optional_decimal("shippingRateWithoutTax")
		found.append(
			Charge(
				SHIPPING,
				option.optional_string("shippingMethodName") or "Shipping",
				cost if cost is not None else amount_of(option, "shippingRate"),
			)
		)
	handling = order.child("handlingFee")
	if handling is not None:
		found.append(
			Charge(FEE, handling.optional_string("name") or "Handling fee", amount_of(handling, "value"))
		)
	for surcharge in surcharges:
		before_tax = surcharge.optional_decimal("totalWithoutTax")
		found.append(
			Charge(
				FEE,
				surcharge.optional_string("description") or "Surcharge",
				before_tax if before_tax is not None else amount_of(surcharge, "total"),
			)
		)
	return [charge for charge in found if charge.amount != 0]


def rated_taxes(node: Node, field: str, amount_field: str = "total") -> list[tuple[str, Decimal, Decimal]]:
	"""Ecwid taxes as (name, rate percent, amount), as ``taxes_of`` reads them."""
	taxes = node.children(field) if isinstance(node.get(field), list) else []
	found = [
		(
			t.optional_string("name") or "Tax",
			t.optional_decimal("value") or Decimal(0),
			t.optional_decimal(amount_field) or amount_of(t, "total"),
		)
		for t in taxes
	]
	return [(name, rate, amount) for name, rate, amount in found if amount]


def inclusive_charges(order: Node, lines: list[OrderLine]) -> tuple[list[OrderLine], list[Charge]]:
	"""A gross-price order's (``pricesIncludeTax``) taxes: each item's an included tax at the item's own
	rates; the shipping option and each surcharge at their prices before tax, each followed by its taxes
	at their rates; the handling fee as it is."""
	amounts: dict[str, Decimal] = {}
	rates: list[LineRates] = []
	for item in order.children("items"):
		line_rates: LineRates = {}
		for name, rate, amount in rated_taxes(item, "taxes", "taxOnDiscountedSubtotal"):
			amounts[name] = amounts.get(name, Decimal(0)) + amount
			line_rates[name] = line_rates.get(name, Decimal(0)) + rate
		rates.append(line_rates)
	lines, found = included_taxes(lines, rates, amounts)
	option = order.child("shippingOption")
	if option is not None:
		shipping_taxes = rated_taxes(order, "taxesOnShipping")
		without_tax = option.optional_decimal("shippingRateWithoutTax")
		net = (
			without_tax
			if without_tax is not None
			else amount_of(option, "shippingRate") - sum((a for _, _, a in shipping_taxes), Decimal(0))
		)
		name = option.optional_string("shippingMethodName") or "Shipping"
		found += taxed_charge(Charge(SHIPPING, name, net), shipping_taxes)
	handling = order.child("handlingFee")
	if handling is not None and amount_of(handling, "value"):
		found.append(
			Charge(FEE, handling.optional_string("name") or "Handling fee", amount_of(handling, "value"))
		)
	surcharges = order.children("customSurcharges") if isinstance(order.get("customSurcharges"), list) else []
	for surcharge in surcharges:
		taxes = rated_taxes(surcharge, "taxes")
		before_tax = surcharge.optional_decimal("totalWithoutTax")
		net = (
			before_tax
			if before_tax is not None
			else amount_of(surcharge, "total") - sum((a for _, _, a in taxes), Decimal(0))
		)
		found += taxed_charge(
			Charge(FEE, surcharge.optional_string("description") or "Surcharge", net), taxes
		)
	return lines, found


class ReviewMapper:
	"""A published product review → an Item Review; one waiting for moderation isn't mirrored."""

	kind = Kind.REVIEW
	version = 1

	def __init__(self, context: Context) -> None:
		self._context = context

	def map(self, node: Node) -> Desired | None:
		if node.optional_string("status") != PUBLISHED:
			return None
		product = linked(node, "productId")
		if product is None:
			raise SourceError(f"Ecwid review {node.string('source_id')} names no product.")
		reviewer = node.child("reviewerInfo")
		fields: Fields = {
			"product": self._context.gid("Product", product),
			"author_name": (reviewer.optional_string("name") if reviewer else None) or "Customer",
			"author_email": ((reviewer.optional_string("email") if reviewer else None) or "").lower() or None,
			"text": node.text("review"),
			"rating": rating_fraction(node.integer("rating"), MAX_RATING),
			"published_on": node.time("createDate")[:10],
		}
		return Desired(self.kind, node.id(), fields)


class RedirectMapper:
	"""An Instant Site redirect → a Website Route Redirect: a target on the store's own site (or a path) is an
	old storefront URL, which redirects on to its mirrored object; a target elsewhere keeps its URL."""

	kind = Kind.URL_REDIRECT
	version = 1

	def map(self, node: Node) -> Desired | None:
		source = path_of(node.string("fromUrl"))
		store_url = node.optional_string("store_url")
		target = redirect_target(node.string("toUrl"), urlsplit(store_url).hostname if store_url else None)
		if source is None or target is None:
			return None
		return Desired(self.kind, node.id(), {"source": source, "target": target, "status": 301})


def mappers(config: ConnectionConfig) -> list[Mapper]:
	context = Context(config)
